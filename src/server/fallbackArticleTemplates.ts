import { countActualWords } from '../utils/articleValidator.ts';

export type CreativeAngleId =
  | 'STORYTELLING_SITE'
  | 'ARTISAN_INSIDER'
  | 'SENSORY_QUIET_LUXURY'
  | 'MYTH_BUSTING_CONSULTANCY'
  | 'REAL_COST_VALUATION'
  | 'ARTISTIC_ALCHEMY';

export interface FallbackArticleResult {
  title: string;
  excerpt: string;
  content: string;
  focusKeyword: string;
  secondaryKeywords: string[];
  tags: string[];
  creativeAngle: CreativeAngleId;
  imageCaptions: string[];
}

const ANGLE_ALIAS_MAP: Record<string, CreativeAngleId> = {
  STORYTELLING_SITE: 'STORYTELLING_SITE',
  CASE_STUDY_REAL_WORLD: 'STORYTELLING_SITE',
  ARTISAN_INSIDER: 'ARTISAN_INSIDER',
  ARTISAN_TRADE_SECRETS: 'ARTISAN_INSIDER',
  SENSORY_QUIET_LUXURY: 'SENSORY_QUIET_LUXURY',
  SENSORY_COLOR_PSYCHOLOGY: 'SENSORY_QUIET_LUXURY',
  MYTH_BUSTING_CONSULTANCY: 'MYTH_BUSTING_CONSULTANCY',
  CONSULTANCY_MYTHBUSTING: 'MYTH_BUSTING_CONSULTANCY',
  REAL_COST_VALUATION: 'REAL_COST_VALUATION',
  ARTISTIC_ALCHEMY: 'ARTISTIC_ALCHEMY',
};

function resolveAngleId(userAngleId?: string, query: string = ''): CreativeAngleId {
  if (userAngleId && ANGLE_ALIAS_MAP[userAngleId]) {
    return ANGLE_ALIAS_MAP[userAngleId];
  }

  const q = query.toLowerCase();
  if (q.includes('تكلف') || q.includes('ميزان') || q.includes('سعر') || q.includes('جدوى')) {
    return 'REAL_COST_VALUATION';
  }
  if (q.includes('جير') || q.includes('limewash') || q.includes('خلط') || q.includes('كيمياء') || q.includes('باليت')) {
    return 'ARTISTIC_ALCHEMY';
  }
  if (q.includes('رطوب') || q.includes('معجون') || q.includes('تأسيس') || q.includes('صنفر')) {
    return 'ARTISAN_INSIDER';
  }
  if (q.includes('لون') || q.includes('جريج') || q.includes('أوف وايت') || q.includes('غرف نوم') || q.includes('قطيف')) {
    return 'SENSORY_QUIET_LUXURY';
  }
  if (q.includes('بديل') || q.includes('رخام') || q.includes('خشب') || q.includes('شاش')) {
    return 'MYTH_BUSTING_CONSULTANCY';
  }

  const all: CreativeAngleId[] = [
    'STORYTELLING_SITE',
    'ARTISAN_INSIDER',
    'SENSORY_QUIET_LUXURY',
    'MYTH_BUSTING_CONSULTANCY',
    'REAL_COST_VALUATION',
    'ARTISTIC_ALCHEMY',
  ];
  return all[Math.floor(Math.random() * all.length)];
}

function buildDraftWeaveBlock(draftContent: string, topicTitle: string, angleId: CreativeAngleId): string {
  const cleanedDraft = draftContent.trim();
  if (!cleanedDraft) return '';

  const introHeaderByAngle: Record<CreativeAngleId, string> = {
    STORYTELLING_SITE: 'من ملاحظات صاحب المشروع في قلب المعاينة الميدانية',
    ARTISAN_INSIDER: 'رؤيتنا الحرفية حول تفاصيل هذا التنفيذ',
    SENSORY_QUIET_LUXURY: 'قراءة حسية ومعمارية لرؤية المكان وتفاصيله',
    MYTH_BUSTING_CONSULTANCY: 'تحليل الخبرة الميدانية لمعطيات الغرفة وأهدافها',
    REAL_COST_VALUATION: 'توصيف بنود الأعمال الأولية وخطة التحسين المالي والفني',
    ARTISTIC_ALCHEMY: 'مرتكزات الباليت اللوني ومواد التكسية المختارة للمشروع',
  };

  return `\n## ${introHeaderByAngle[angleId]}: ${topicTitle}\n\n${cleanedDraft}\n\nانطلاقاً من هذه المعطيات الواقعية، بنينا خطة التشطيب خطوة بخطوة بحيث تجمع بين جماليات الدهان العصري ومتانة التأسيس على المدى الطويل.\n`;
}

